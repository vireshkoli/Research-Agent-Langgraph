"""Write requirements.txt from pyproject.toml's direct dependencies.

Only Hugging Face Gradio Spaces read this file; everything else installs from
uv.lock. It is direct dependencies with loose bounds on purpose: a fully-pinned
`uv export` was tried first and the Space build failed, because the builder
layers its own exact pins for gradio[oauth,mcp] and spaces on top and pip cannot
reconcile two complete sets of pins. Loose direct deps let pip resolve against
whatever the builder brings.
"""

import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = """\
# Direct dependencies only, for Hugging Face Gradio Spaces. Generated by
# scripts/requirements.py from pyproject.toml — edit that, not this.
#
# Deliberately not a full lock export: the Space builder adds its own exact pins
# for gradio[oauth,mcp] and spaces, and pip cannot reconcile those with a second
# complete set. uv.lock remains the reproducible source of truth everywhere else.
"""


def main() -> None:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    body = "\n".join(project["dependencies"]) + "\n"
    (ROOT / "requirements.txt").write_text(HEADER + body)
    print(f"wrote requirements.txt ({len(project['dependencies'])} direct dependencies)")


if __name__ == "__main__":
    main()
